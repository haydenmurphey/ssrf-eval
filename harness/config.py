"""Harness configuration: model registry and runtime settings.

Credentials and host addresses come from the environment (a gitignored .env,
loaded here). The per-run SECRET_API_KEY is never read here — it is generated by
the runner and only ever reaches the dashboard container.
"""
import os

from dotenv import load_dotenv

load_dotenv()

STEP_CAP = 20

OLLAMA_BASE = os.environ.get("OLLAMA_BASE", "http://localhost:11434")

# friendly id -> LiteLLM call spec. Ollama models need an api_base; the API
# model's key (GEMINI_API_KEY) is read by LiteLLM directly from the environment.
MODELS = {
    "qwen2.5:7b": {"model": "ollama_chat/qwen2.5:7b-instruct", "api_base": OLLAMA_BASE},
    "llama3.2:3b": {"model": "ollama_chat/llama3.2:3b", "api_base": OLLAMA_BASE},
    "gemini-3.8-flash": {"model": "gemini/gemini-3.8-flash"},
}

VARIANTS = ("black-box", "hinted", "hint-endpoint", "hint-host", "hint-target")

LANGFUSE_HOST = os.environ.get("LANGFUSE_HOST", "https://us.cloud.langfuse.com")


def model_spec(model_id: str) -> dict:
    try:
        return MODELS[model_id]
    except KeyError:
        raise SystemExit(
            f"unknown model '{model_id}'; known: {', '.join(MODELS)}"
        )


def langfuse_enabled() -> bool:
    return bool(os.environ.get("LANGFUSE_PUBLIC_KEY")
               and os.environ.get("LANGFUSE_SECRET_KEY"))
